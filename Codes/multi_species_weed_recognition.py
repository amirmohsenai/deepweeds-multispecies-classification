def _zenodo_metadata() -> tuple[str, int, str]:
    """Read official Zenodo size/checksum at runtime."""
    response = requests.get(
        ZENODO_RECORD_API,
        headers={
            "User-Agent":
            "Mozilla/5.0 "
            "(Colab DeepWeeds downloader)"
        },
        timeout=(30, 60),
    )

    response.raise_for_status()

    record = response.json()

    for file_info in record.get(
        "files",
        [],
    ):

        key = str(
            file_info.get("key")
            or file_info.get("name")
            or ""
        )

        if (
            key.lower()
            != "images.zip"
        ):
            continue

        size = int(
            file_info.get("size")
            or 0
        )

        checksum = str(
            file_info.get("checksum")
            or ""
        )

        if checksum.startswith(
            "md5:"
        ):
            checksum = checksum[4:]

        url = (
            file_info
            .get("links", {})
            .get("self")
            or file_info
            .get("links", {})
            .get("download")
            or ZENODO_IMAGE_URL
        )

        return (
            str(url),
            size,
            checksum,
        )

    return (
        ZENODO_IMAGE_URL,
        0,
        "b7b30f96d466fba86016aa5a26606e0f",
    )


def _md5(
    path: Path,
) -> str:

    digest = hashlib.md5()

    with path.open(
        "rb"
    ) as f:

        for chunk in iter(
            lambda:
            f.read(
                8 * 1024 * 1024
            ),
            b"",
        ):
            digest.update(
                chunk
            )

    return digest.hexdigest()


def _download_zenodo_verified(
    destination: Path,
) -> Path:
    """
    Download Zenodo and reject anything that
    fails size + MD5 + ZIP CRC verification.
    """
    (
        url,
        expected_size,
        expected_md5,
    ) = _zenodo_metadata()

    part = destination.with_name(
        destination.name + ".part"
    )

    if part.exists():
        part.unlink()

    print(
        "Using Zenodo as the final "
        "verified fallback..."
    )

    print(
        "Source:",
        url,
    )

    if expected_size:
        print(
            "Expected size: "
            f"{expected_size / (1024**2):.2f} MiB"
        )

    print(
        "Expected MD5:",
        expected_md5,
    )

    cmd = [
        "curl",
        "-L",
        "--fail",
        "--show-error",
        "--progress-bar",
        "--retry",
        "5",
        "--retry-delay",
        "3",
        "--retry-all-errors",
        "--connect-timeout",
        "30",
        "--max-time",
        "1800",
        "-A",
        "Mozilla/5.0 "
        "(Colab DeepWeeds downloader)",
        "-o",
        str(part),
        url,
    ]

    result = subprocess.run(
        cmd,
        check=False,
    )

    if result.returncode != 0:
        raise RuntimeError(
            "Zenodo curl failed with "
            f"exit code {result.returncode}."
        )

    actual_size = (
        part.stat().st_size
        if part.exists()
        else 0
    )

    if (
        expected_size
        and actual_size
        != expected_size
    ):
        raise RuntimeError(
            "Zenodo size mismatch: "
            f"got {actual_size} bytes, "
            f"expected {expected_size} bytes."
        )

    actual_md5 = _md5(
        part
    )

    print(
        "Actual MD5:",
        actual_md5,
    )

    if (
        actual_md5.lower()
        != expected_md5.lower()
    ):
        raise RuntimeError(
            "Zenodo MD5 mismatch; "
            "refusing to accept the archive."
        )

    if not _validate_zip_archive(
        part
    ):
        raise RuntimeError(
            "Zenodo archive passed MD5 "
            "but failed DeepWeeds ZIP validation."
        )

    part.replace(
        destination
    )

    print(
        "Verified Zenodo archive:",
        destination,
    )

    return destination


