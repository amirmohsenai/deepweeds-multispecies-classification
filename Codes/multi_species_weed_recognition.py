def _extract_confirm_token(
    html: str,
) -> Optional[str]:

    patterns = [
        r"confirm=([0-9A-Za-z_-]+)",
        r'name="confirm"[^>]+value="([^"]+)"',
        r"name='confirm'[^>]+value='([^']+)'",
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            html,
        )

        if match:
            return match.group(1)

    return None


def _download_drive_route(
    url: str,
    part: Path,
) -> Path:
    """
    Download one Drive route and immediately reject
    HTML/non-ZIP content.
    """
    if part.exists():
        part.unlink()

    print(
        "Trying official DeepWeeds "
        "Google Drive source:"
    )

    print(
        " ",
        url,
    )

    with requests.get(
        url,
        headers={
            "User-Agent":
            "Mozilla/5.0 "
            "(Colab DeepWeeds downloader)"
        },
        stream=True,
        allow_redirects=True,
        timeout=(30, 180),
    ) as response:

        response.raise_for_status()

        content_type = (
            response.headers.get(
                "Content-Type"
            )
            or ""
        ).lower()

        if "text/html" in content_type:
            raise RuntimeError(
                "Google Drive returned HTML "
                "instead of the ZIP file."
            )

        with part.open(
            "wb"
        ) as out:

            first = True

            total_bytes = int(response.headers.get("Content-Length", 0) or 0)
            progress = tqdm(
                total=total_bytes or None,
                unit="B",
                unit_scale=True,
                desc="Downloading DeepWeeds",
                leave=True,
            )

            try:
                for chunk in response.iter_content(
                    chunk_size=8 * 1024 * 1024
                ):
                    if not chunk:
                        continue

                    if first:
                        first = False
                        if not chunk.startswith(b"PK"):
                            raise RuntimeError(
                                "Google Drive returned a non-ZIP payload; "
                                f"first bytes={chunk[:32]!r}"
                            )

                    out.write(chunk)
                    progress.update(len(chunk))
            finally:
                progress.close()

    if not _validate_zip_archive(
        part
    ):
        raise RuntimeError(
            "The Drive download completed "
            "but failed strict ZIP validation."
        )

    return part


def _download_google_drive_original_flow(
    destination: Path,
) -> Path:
    """
    Use the same confirmation-token idea
    as the original DeepWeeds downloader.
    """
    part = destination.with_name(
        destination.name + ".part"
    )

    if part.exists():
        part.unlink()

    session = requests.Session()

    session.headers.update(
        {
            "User-Agent":
            "Mozilla/5.0 "
            "(Colab DeepWeeds downloader)"
        }
    )

    base = (
        "https://docs.google.com/uc?"
        "export=download"
    )

    response = session.get(
        base,
        params={
            "id":
            IMAGE_GDRIVE_FILE_ID
        },
        stream=True,
        allow_redirects=True,
        timeout=(30, 180),
    )

    response.raise_for_status()

    token = next(
        (
            value
            for key, value
            in response.cookies.items()
            if key.startswith(
                "download_warning"
            )
        ),
        None,
    )

    if token is None:

        content_type = (
            response.headers.get(
                "Content-Type"
            )
            or ""
        ).lower()

        if "text/html" in content_type:
            token = _extract_confirm_token(
                response.text[:100_000]
            )

    if token:

        response.close()

        response = session.get(
            base,
            params={
                "id":
                IMAGE_GDRIVE_FILE_ID,
                "confirm":
                token,
            },
            stream=True,
            allow_redirects=True,
            timeout=(30, 180),
        )

        response.raise_for_status()

    content_type = (
        response.headers.get(
            "Content-Type"
        )
        or ""
    ).lower()

    if "text/html" in content_type:

        response.close()

        raise RuntimeError(
            "Google Drive confirmation flow "
            "returned HTML instead of ZIP data."
        )

    try:

        with part.open(
            "wb"
        ) as out:

            first = True

            total_bytes = int(response.headers.get("Content-Length", 0) or 0)
            progress = tqdm(
                total=total_bytes or None,
                unit="B",
                unit_scale=True,
                desc="Downloading DeepWeeds",
                leave=True,
            )

            try:
                for chunk in response.iter_content(
                    chunk_size=8 * 1024 * 1024
                ):
                    if not chunk:
                        continue

                    if first:
                        first = False
                        if not chunk.startswith(b"PK"):
                            raise RuntimeError(
                                "Confirmation flow returned a non-ZIP payload; "
                                f"first bytes={chunk[:32]!r}"
                            )

                    out.write(chunk)
                    progress.update(len(chunk))
            finally:
                progress.close()

    finally:
        response.close()

    if not _validate_zip_archive(
        part
    ):
        raise RuntimeError(
            "Original Google Drive flow "
            "produced an invalid DeepWeeds ZIP."
        )

    return part


def _download_official_google_drive(
    destination: Path,
) -> Path:

    part = destination.with_name(
        destination.name + ".part"
    )

    errors = []

    for route in (
        IMAGE_GDRIVE_USERCONTENT_URL,
        IMAGE_GDRIVE_URL,
    ):

        try:
            return _download_drive_route(
                route,
                part,
            )

        except Exception as exc:

            errors.append(
                str(exc)
            )

            if part.exists():
                part.unlink()

    try:

        print(
            "Trying the original DeepWeeds "
            "Google Drive confirmation flow..."
        )

        return _download_google_drive_original_flow(
            destination
        )

    except Exception as exc:

        errors.append(
            str(exc)
        )

        if part.exists():
            part.unlink()

    raise RuntimeError(
        "Official Google Drive routes failed: "
        + " | ".join(errors)
    )


