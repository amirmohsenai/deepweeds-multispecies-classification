def _capture_group_from_filename(
    path: Path,
) -> tuple[str, str]:

    """
    DeepWeeds filenames follow:
        YYYYMMDD-HHMMSS-ID

    Grouping key:
        capture date + instrument ID

    Fallback:
        image stem
    """

    stem = path.stem

    match = re.match(
        r"^(\d{8})-(\d{6})-(\d+)$",
        stem,
    )

    if match:

        date = match.group(1)
        instrument = match.group(3)

        return (
            f"{date}_camera{instrument}",
            date,
        )

    return (
        stem,
        stem,
    )


