def _validate_zip_archive(
    path: Path,
) -> bool:
    """
    Require:
      1. ZIP format
      2. exactly 17,509 images
      3. valid ZIP CRCs

    The result is memoized for an unchanged path so repeated routing checks
    do not repeatedly walk/decompress the same multi-gigabyte archive.
    """
    path = Path(path)

    if (
        not path.is_file()
        or not _is_supported_archive(path)
    ):
        return False

    stat = path.stat()
    cache_key = (
        str(path.resolve()),
        int(stat.st_size),
        int(stat.st_mtime_ns),
    )
    cached = _ZIP_VALIDATION_CACHE.get(cache_key)
    if cached is not None:
        return bool(cached)

    if not zipfile.is_zipfile(path):
        _ZIP_VALIDATION_CACHE[cache_key] = False
        return False

    try:
        with zipfile.ZipFile(
            path,
            "r",
        ) as zf:

            infos = zf.infolist()

            image_infos = [
                info
                for info in infos
                if (
                    not info.is_dir()
                    and Path(
                        info.filename.replace(
                            "\\",
                            "/",
                        )
                    ).suffix.lower()
                    in IMAGE_EXTENSIONS
                )
            ]

            if (
                len(image_infos)
                != EXPECTED_IMAGE_COUNT
            ):
                _ZIP_VALIDATION_CACHE[cache_key] = False
                return False

            bad_member = zf.testzip()

            if bad_member is not None:
                print(
                    "ZIP CRC check failed at:",
                    bad_member,
                )

                _ZIP_VALIDATION_CACHE[cache_key] = False
                return False

        _ZIP_VALIDATION_CACHE[cache_key] = True
        return True

    except (
        OSError,
        zipfile.BadZipFile,
        RuntimeError,
    ):
        _ZIP_VALIDATION_CACHE[cache_key] = False
        return False


