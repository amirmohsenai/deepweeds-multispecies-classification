def _find_drive_archive(
    search_root: Path,
) -> Optional[Path]:
    """Find only a strictly validated DeepWeeds ZIP in Drive."""
    if not search_root.exists():
        return None

    direct = [
        DRIVE_DATASET_ARCHIVE,
        search_root / "DeepWeeds_images.zip",
        search_root / "DeepWeeds_dataset.zip",
        (
            search_root
            / "Datasets"
            / "DeepWeeds"
            / "DeepWeeds_images.zip"
        ),
        (
            search_root
            / "datasets"
            / "DeepWeeds"
            / "DeepWeeds_images.zip"
        ),
    ]

    for candidate in direct:

        if (
            candidate.is_file()
            and _validate_zip_archive(candidate)
        ):
            return candidate.resolve()

    base_depth = len(
        search_root.resolve().parts
    )

    for current, dirs, files in os.walk(
        search_root
    ):

        current = Path(current)

        depth = (
            len(current.parts)
            - base_depth
        )

        if depth > 4:
            dirs[:] = []
            continue

        dirs[:] = [
            d
            for d in dirs
            if not d.startswith(".")
            and d not in {
                "node_modules",
                "__pycache__",
                "venv",
                ".venv",
            }
        ]

        for filename in files:

            if (
                "deepweed"
                not in filename.lower()
            ):
                continue

            candidate = (
                current / filename
            )

            if (
                _is_supported_archive(
                    candidate
                )
                and _validate_zip_archive(
                    candidate
                )
            ):
                return candidate.resolve()

    return None


